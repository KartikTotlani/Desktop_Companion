// Character animation types.
// Pure data definitions: no React, DOM, canvas or Tauri imports.
// Only erasable TypeScript syntax is used (no enums or parameter properties)
// so these modules can also be executed directly by Node's type stripping in tests.

/** Animation clips supported by the first character release. */
export const CLIP_IDS = ["idle", "hop", "react"] as const;
export type ClipId = (typeof CLIP_IDS)[number];

/** Interaction events the state machine accepts from the overlay. */
export const INTERACTION_EVENTS = ["click", "hoverEnter"] as const;
export type InteractionEvent = (typeof INTERACTION_EVENTS)[number];

/** What a clip does when its own trigger arrives while it is already playing. */
export type Retrigger = "ignore" | "queue";

export interface Size {
  w: number;
  h: number;
}

export interface Point {
  x: number;
  y: number;
}

export interface ClipDef {
  /** Atlas path relative to the manifest file. */
  atlas: string;
  columns: number;
  frames: number;
  fps: number;
  /** Optional per-frame durations in ms; overrides `fps` when present. */
  durations?: number[];
  loop: boolean;
  priority: number;
  /** Clip to play when a one-shot finishes. */
  next?: ClipId;
  retrigger?: Retrigger;
  /** For one-shots: clips allowed to interrupt this clip. */
  interruptibleBy?: ClipId[];
  preload?: boolean;
}

/** Precomputed silhouette hit mask (generated by the atlas pack tool later). */
export interface HitMaskDef {
  w: number;
  h: number;
  alphaThreshold: number;
  dilate: number;
  /** Base64 of the packed 1-bit mask. */
  data: string;
}

export interface CharacterManifest {
  schema: 1;
  character: string;
  version: string;
  /** Window size in logical (CSS) pixels. */
  logicalSize: Size;
  /** Shipped frame size in pixels. */
  frameSize: Size;
  /** Feet anchor in shipped-frame pixels. */
  anchor: Point;
  /** Minimum time between accepted hover reactions, in ms. */
  hoverCooldownMs: number;
  clips: Record<ClipId, ClipDef>;
  /** Interaction event to clip. Validated to the enforced mapping. */
  events: Record<InteractionEvent, ClipId>;
  hit?: HitMaskDef;
}

/** Immutable state of the animation state machine. */
export interface MachineState {
  clip: ClipId;
  /** Timestamp (ms) at which the current clip started. */
  clipStartedAt: number;
  /** True when one extra repeat of the current clip is queued. */
  queued: boolean;
  /** Timestamp (ms) of the last accepted hover reaction, or null. */
  lastHoverAt: number | null;
}
